function decode(bytes) {
  return Uint8Array.from(atob(bytes),character=>character.charCodeAt(0));
}

const fractions=decode(surfaceFractions);
const coast=decode(coastMask);
const degrees=Math.PI/180;
const cellAngle=360/CRYO_GRID_WIDTH;

export const CRYO_CELLS=Object.freeze(Array.from({length:CRYO_GRID_WIDTH*CRYO_GRID_HEIGHT},(_,index)=>{
  const row=Math.floor(index/CRYO_GRID_WIDTH);
  const north=90-row*cellAngle;
  const south=north-cellAngle;
  return Object.freeze({
    latitude:(north+south)/2,
    longitude:-180+(index%CRYO_GRID_WIDTH+.5)*cellAngle,
    landFraction:fractions[index*2]/255,
    glacierFraction:fractions[index*2+1]/255,
    elevation:null,
    areaFraction:(Math.sin(north*degrees)-Math.sin(south*degrees))/(2*CRYO_GRID_WIDTH)
  });
}));

function gridIndex(latitude,longitude,width,height) {
  if (!Number.isFinite(latitude) || !Number.isFinite(longitude)) return -1;
  const lat=Math.max(-90,Math.min(90,latitude));
  const lon=((longitude+180)%360+360)%360;
  const row=Math.min(height-1,Math.floor((90-lat)*height/180));
  return row*width+Math.floor(lon*width/360);
}

export function cryoCellIndex(latitude,longitude) {
  return gridIndex(latitude,longitude,CRYO_GRID_WIDTH,CRYO_GRID_HEIGHT);
}

export function cryoLandAt(latitude,longitude) {
  const index=gridIndex(latitude,longitude,360,180);
  return index>=0 && Boolean(coast[index>>3] & (1<<(index%8)));
}

